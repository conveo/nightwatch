#!/usr/bin/env perl
# Denylist gate. Fails (exit 1) when any file, or any commit in the git history,
# contains a denylisted pattern that no allow rule covers.
#
#   perl scripts/sync/denylist-gate.pl --denylist <file> --tree <dir>
#   perl scripts/sync/denylist-gate.pl --denylist <file> --history <repo>
#
# The denylist is NOT committed: it names the private things this repo must not
# contain, so publishing it would publish them. Keep it outside the repo, or in
# scripts/sync/denylist.local.txt (gitignored). Format: see denylist.example.txt.
use strict;
use warnings;
use File::Find;
use Getopt::Long;

my ($denylist, $tree, $history, $show_allowed);
GetOptions('denylist=s' => \$denylist, 'tree=s' => \$tree, 'history=s' => \$history, 'show-allowed' => \$show_allowed)
  or die "bad arguments\n";
die "usage: denylist-gate.pl --denylist <file> (--tree <dir> | --history <repo>)\n"
  unless defined $denylist && (defined $tree || defined $history);
die "denylist not found: $denylist\n" unless -f $denylist;

my (@deny, @allow);
open my $fh, '<', $denylist or die "read $denylist: $!\n";
while (my $line = <$fh>) {
  chomp $line;
  next if $line =~ /^\s*(#|$)/;
  if ($line =~ /^allow\t([^\t]+)\t([^\t]+)\t?(.*)$/) {
    # allow <TAB> path-regex <TAB> line-regex <TAB> justification
    push @allow, { path => qr/$1/, text => qr/$2/i, why => $3 };
    next;
  }
  # Patterns are Perl regexes, case-insensitive unless they start with (?-i).
  push @deny, { src => $line, re => qr/(?i)$line/ };
}
close $fh;
die "denylist has no patterns\n" unless @deny;

my $hits = 0;
my $allowed = 0;

sub check_line {
  my ($where, $path, $text) = @_;
  for my $d (@deny) {
    next unless $text =~ $d->{re};
    my $ok = 0;
    for my $a (@allow) {
      if ($path =~ $a->{path} && $text =~ $a->{text}) { $ok = 1; last }
    }
    if ($ok) {
      $allowed++;
      print "ALLOW [$d->{src}]  $where\n" if $show_allowed;
      next;
    }
    $hits++;
    my $show = $text;
    $show =~ s/^\s+//;
    $show = substr($show, 0, 160);
    print "HIT  [$d->{src}]  $where: $show\n";
  }
}

if (defined $tree) {
  $tree =~ s{/+$}{};
  my @files;
  find({ no_chdir => 1, wanted => sub {
    if (-d $_ && $_ =~ m{/(node_modules|\.git|dist)$}) { $File::Find::prune = 1; return }
    # The console's Prisma client: generated by pnpm install, gitignored, and
    # full of base64 that matches short patterns by chance.
    if (-d $_ && $_ =~ m{/agent-mesh/src/generated$}) { $File::Find::prune = 1; return }
    push @files, $File::Find::name if -f $_;
  } }, $tree);
  for my $abs (sort @files) {
    (my $rel = $abs) =~ s{^\Q$tree\E/}{};
    # The denylist itself is local and gitignored; never scan it.
    next if $rel =~ m{(^|/)denylist\.local\.txt$};
    check_line("$rel (path)", $rel, $rel);
    open my $in, '<:raw', $abs or die "read $abs: $!\n";
    my $n = 0;
    while (my $l = <$in>) {
      $n++;
      # Binary files are scanned too: a PNG or lockfile can embed text.
      check_line("$rel:$n", $rel, $l);
    }
    close $in;
  }
}

if (defined $history) {
  # Every commit: author/committer identity, message, and full patch.
  open my $git, '-|', 'git', '-C', $history, 'log', '--all', '--format=commit %H%nauthor %an <%ae>%ncommitter %cn <%ce>%n%B', '-p', '--no-color', '--text'
    or die "git log failed: $!\n";
  my ($commit, $file) = ('', '');
  while (my $l = <$git>) {
    if ($l =~ /^commit ([0-9a-f]{40})$/) { $commit = substr($1, 0, 10); $file = '(message)'; next }
    if ($l =~ m{^\+\+\+ b/(.*)$}) { $file = $1; next }
    if ($l =~ /^(author|committer) /) { check_line("$commit $1", "(identity)", $l); next }
    next if $l =~ /^(diff --git|index |--- |\+\+\+ )/;
    check_line("$commit $file", $file, $l);
  }
  close $git;
}

print "denylist gate: $hits unjustified hit(s), $allowed allowed hit(s)\n";
exit($hits ? 1 : 0);
